using System.Text;
using System.Text.Json;

namespace CS2Panel;

internal static class OffsetGenerator
{
    /// <summary>cs2-dumper client.dll 全局偏移；游戏更新后部分项可能缺失（如 dwSensitivity）。</summary>
    private static readonly string[] RequiredGlobalOffsets =
    [
        "dwEntityList",
        "dwLocalPlayerPawn",
        "dwLocalPlayerController",
        "dwViewMatrix",
        "dwViewAngles",
        "dwGameEntitySystem_highestEntityIndex",
    ];

    /// <summary>当前 dumper 可能扫不到；ESP 未使用，有则写入。</summary>
    private static readonly string[] OptionalGlobalOffsets =
    [
        "dwSensitivity",
        "dwSensitivity_sensitivity",
    ];

    private static readonly (string Class, string Field)[] SchemaFields =
    [
        ("CCSPlayerController", "m_hPlayerPawn"),
        ("CCSPlayerController", "m_iszPlayerName"),
        ("C_BaseEntity", "m_iHealth"),
        ("C_BaseEntity", "m_lifeState"),
        ("C_BaseEntity", "m_iTeamNum"),
        ("C_BaseEntity", "m_pGameSceneNode"),
        ("CSkeletonInstance", "m_modelState"),
        ("C_BaseModelEntity", "m_vecViewOffset"),
        ("CGameSceneNode", "m_vecAbsOrigin"),
        ("C_CSPlayerPawn", "m_angEyeAngles"),
        ("C_CSPlayerPawn", "m_iShotsFired"),
        ("C_CSPlayerPawn", "m_pCameraServices"),
        ("C_CSPlayerPawn", "m_pAimPunchServices"),
        ("C_CSPlayerPawn", "m_pWeaponServices"),
        ("CPlayer_WeaponServices", "m_hActiveWeapon"),
        ("C_EconEntity", "m_AttributeManager"),
        ("C_AttributeContainer", "m_Item"),
        ("C_EconItemView", "m_iItemDefinitionIndex"),
        ("C_BasePlayerPawn", "v_angle"),
        ("CPlayer_CameraServices", "m_vecCsViewPunchAngle"),
        ("CCSPlayer_AimPunchServices", "m_unpredictableBaseAngle"),
    ];

    public static string Generate(string offsetsJsonPath, string clientDllJsonPath)
    {
        using var offsetsDoc = JsonDocument.Parse(File.ReadAllText(offsetsJsonPath));
        if (!offsetsDoc.RootElement.TryGetProperty("client.dll", out var clientModule))
            throw new InvalidOperationException("offsets.json missing client.dll section.");

        var globals = new Dictionary<string, long>();
        foreach (var name in RequiredGlobalOffsets)
        {
            if (!clientModule.TryGetProperty(name, out var prop))
                throw new InvalidOperationException($"offsets.json missing client.dll.{name}");
            globals[name] = prop.GetInt64();
        }

        foreach (var name in OptionalGlobalOffsets)
        {
            if (clientModule.TryGetProperty(name, out var prop))
                globals[name] = prop.GetInt64();
        }

        using var clientDoc = JsonDocument.Parse(File.ReadAllText(clientDllJsonPath));
        if (!clientDoc.RootElement.TryGetProperty("client.dll", out var clientRoot))
            throw new InvalidOperationException("client_dll.json missing client.dll section.");
        if (!clientRoot.TryGetProperty("classes", out var classes))
            throw new InvalidOperationException("client_dll.json missing classes.");

        var schemas = new Dictionary<string, long>();
        foreach (var (className, fieldName) in SchemaFields)
        {
            var offset = TryGetFieldOffset(classes, className, fieldName)
                         ?? FindFieldInAnyClass(classes, fieldName)
                         ?? throw new InvalidOperationException(
                             $"Field {fieldName} not found (expected in {className}).");
            schemas[fieldName] = offset;
        }

        var sb = new StringBuilder();
        sb.AppendLine("#pragma once");
        sb.AppendLine();
        sb.AppendLine("#include <cstddef>");
        sb.AppendLine("#include <cstdint>");
        sb.AppendLine();
        sb.AppendLine("// Auto-generated by CS2Panel from cs2-dumper output.");
        sb.AppendLine($"// {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine();
        sb.AppendLine("namespace sdk::offsets {");
        sb.AppendLine();
        sb.AppendLine("// CGameEntitySystem list entry stride; update if list iteration breaks.");
        sb.AppendLine("inline constexpr std::ptrdiff_t kEntityStride = 0x70;");
        sb.AppendLine();

        foreach (var (name, value) in globals)
            sb.AppendLine($"inline constexpr std::ptrdiff_t {name} = {value};");

        sb.AppendLine();
        sb.AppendLine("namespace schemas {");
        sb.AppendLine();

        foreach (var (name, value) in schemas)
            sb.AppendLine($"inline constexpr std::ptrdiff_t {name} = {value};");

        sb.AppendLine();
        sb.AppendLine("} // namespace schemas");
        sb.AppendLine();
        sb.AppendLine("} // namespace sdk::offsets");
        sb.AppendLine();

        return sb.ToString();
    }

    private static long? TryGetFieldOffset(JsonElement classes, string className, string fieldName)
    {
        if (!classes.TryGetProperty(className, out var cls))
            return null;
        if (!cls.TryGetProperty("fields", out var fields))
            return null;
        if (!fields.TryGetProperty(fieldName, out var off))
            return null;
        return off.GetInt64();
    }

    private static long? FindFieldInAnyClass(JsonElement classes, string fieldName)
    {
        foreach (var cls in classes.EnumerateObject())
        {
            if (!cls.Value.TryGetProperty("fields", out var fields))
                continue;
            if (fields.TryGetProperty(fieldName, out var off))
                return off.GetInt64();
        }

        return null;
    }
}
